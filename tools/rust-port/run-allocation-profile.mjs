import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {gzipSync} from 'node:zlib';
import assert from 'node:assert/strict';
import {runMonitored} from './one-battle-check-support.mjs';
import {compareNativeReports,firstDifference} from '../native-report-compare.mjs';
const root=resolve(import.meta.dirname,'../..');
const args=process.argv.slice(2),option=(name,fallback)=>args.includes(name)?args[args.indexOf(name)+1]:fallback;
assert.ok(args.includes('--run'),'Explicit --run required; reserve CPU/memory slot first.');
const proofFile=resolve(root,option('--proof','benchmarks/validation/rust-allocation-profile-2026-10-28T21-15-16.648Z.json'));
const stamp=new Date().toISOString().replaceAll(':','-');
const output=resolve(root,option('--output',`benchmarks/results/${stamp}-rust-measured-allocations.json`));
const prefix=output.replace(/\.json$/,'');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const proofBytes=await readFile(proofFile),proof=JSON.parse(proofBytes);
const baseline=JSON.parse(await readFile(proof.baseline.file));
assert.equal(baseline.passed,true);
const inputs=[proof.binary,proof.wrapper,...proof.libraries,proof.allocationCounter];
for(const row of inputs)assert.equal(sha(await readFile(row.file)),row.sha256,'Changed input '+row.file);
const stdoutFile=prefix+'.stdout',stderrFile=prefix+'.stderr';
const execution=await runMonitored([proof.binary.file],{cwd:root,env:{...process.env,RUST_PORT_TRACE:'0'},stdoutFile,stderrFile,maxRssKiB:8*1024*1024,timeoutMs:180000});
const stdout=await readFile(stdoutFile),stderr=await readFile(stderrFile),text=stderr.toString();
const reports=stdout.toString().trim().split('\n').flatMap(line=>{try{const value=JSON.parse(line);return value?.completed===20?[value]:[]}catch{return[]}});
const counts=[...text.matchAll(/^MEASURED_ALLOCATIONS:(\{.*\})$/gm)].map(row=>JSON.parse(row[1]));
const changedInputs=[];
for(const row of inputs)if(sha(await readFile(row.file))!==row.sha256)changedInputs.push(row.file);
const difference=reports.length===1?compareNativeReports(reports[0],baseline.referenceReport):'Missing unique full report';
const hostDifference=reports.length===1?firstDifference(reports[0].hostInputConsumption,baseline.referenceReport.hostInputConsumption,'$.hostInputConsumption'):'Missing report';
const artifacts=[];
for(const [label,bytes] of [['stdout',stdout],['stderr',stderr]]){const compressed=gzipSync(bytes),file=prefix+'.'+label+'.gz';await writeFile(file,compressed);artifacts.push({file,sha256:sha(compressed),uncompressedSha256:sha(bytes)});}
const passed=execution.status===0&&execution.signal==null&&counts.length===1&&difference===null&&hostDifference===null&&changedInputs.length===0;
const report={version:1,passed,qualifiesFor10000Target:false,scope:'Instrumented allocation diagnostic over original twenty measured/three warmup native battles. Full non-timing report and host input consumption checked against pinned Node. Atomic allocator accounting changes timing; reported BPS is not an uninstrumented performance result. Requested byte traffic is not live or peak memory.',preparation:{file:proofFile,sha256:sha(proofBytes)},baseline:proof.baseline,execution,counts:counts[0]??null,perBattle:counts.length===1?Object.fromEntries(Object.entries(counts[0]).map(([key,value])=>[key,value/20])):null,difference,hostDifference,changedInputs,report:reports[0]??null,artifacts};
await writeFile(output,JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({output,passed,perBattle:report.perBattle,difference,hostDifference,changedInputs}));
if(!passed)process.exitCode=1;
