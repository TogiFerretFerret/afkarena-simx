import { parse, parseExpression } from '@babel/parser';
import traverse from '@babel/traverse';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { staticName } from './source-index.mjs';

// A narrow, shape-checked intrinsic lowering. This is not a general stateful-JS lowering.
const expected = {
  'ed.rand': 'function(){var e=random_seed*multiplier%moder,t=e/moder;return random_seed=e,ed.btLog.append("rand --> "+t),t}',
  'ed.randDontChangeSeed': 'function(){return random_seed*multiplier%moder/moder}',
  'ed.srand': 'function(e){ed.init_battle_seed=e,e&&0!==e||(cc.error("Error:srand(0)"),e=1),e=Math.floor((moder-e)/e),ed.btLog.append("srand --> "+e),random_seed=e}',
};
function semanticTree(node) {
  if (Array.isArray(node)) return node.map(semanticTree);
  if (!node || typeof node !== 'object') return node;
  return Object.fromEntries(Object.entries(node)
    .filter(([key]) => !['start','end','loc','extra','comments','errors','leadingComments','trailingComments','innerComments'].includes(key))
    .map(([key,value])=>[key,semanticTree(value)]));
}
const root = resolve(import.meta.dirname, '..');
const sourcePath = 'src/srcmodule/game_util.js';
const source = await readFile(resolve(root, sourcePath), 'utf8');
const found = new Map();
const constants = {};
traverse(parse(source, { sourceType: 'script' }), {
  Program(path) {
    for (const [name, expression] of Object.entries({ multiplier:'25', moder:'Math.pow(2,35)-31' })) {
      const binding = path.scope.getBinding(name);
      assert.ok(binding?.constant, `${name} must have no syntactic reassignment in this script`);
      assert.deepEqual(semanticTree(binding.path.node.init), semanticTree(parseExpression(expression)));
      constants[name] = { start: binding.path.node.init.start, end: binding.path.node.init.end };
    }
  },
  AssignmentExpression(path) {
    const name = staticName(path.node.left);
    if (!(name in expected)) return;
    assert.equal(path.node.operator, '=');
    assert.ok(!found.has(name), `Duplicate definition: ${name}`);
    const fn = path.node.right;
    assert.deepEqual(semanticTree(fn), semanticTree(parseExpression(expected[name])), `Unrecognized RNG function: ${name}`);
    found.set(name, { name, start: fn.start, end: fn.end,
      sha256: createHash('sha256').update(source.slice(fn.start, fn.end)).digest('hex') });
  },
});
assert.equal(found.size, Object.keys(expected).length);
const manifest = {
  version: 1, source: sourcePath, translation: 'shape_checked_intrinsic_template',
  formalProof: false,
  domain: [
    'Seeds and RNG state are JavaScript Number values, represented as binary64',
    'multiplier and moder retain their source initializers; Math.floor and Math.pow are standard intrinsics',
    'Logging and error observers do not throw, reenter, mutate RNG state, or affect battle decisions',
    'Observer events preserve numeric values, callback order and visible RNG state; exact JS log-string rendering is not implemented',
    'NaN payload and sign are not specified by JS; other numeric outputs retain their bits'
  ],
  arithmetic: { multiplier: 25, modulus: 34359738337 }, constants,
  functions: [...found.values()],
};
const outputs = [
  ['crates/battle-core/src/rng.rs', '// Generated by tools/generate-rng.mjs from a shape-checked template.\n' + await readFile(resolve(root, 'tools/templates/rng.rs'), 'utf8')],
  ['config/rng-translation.json', JSON.stringify(manifest, null, 2) + '\n'],
];
for (const [path, contents] of outputs) {
  if (process.argv.includes('--check')) assert.equal(await readFile(resolve(root,path),'utf8'), contents, `Stale: ${path}`);
  else await writeFile(resolve(root,path), contents);
}
console.log(`${process.argv.includes('--check') ? 'Checked' : 'Generated'} shape-checked RNG intrinsic`);
